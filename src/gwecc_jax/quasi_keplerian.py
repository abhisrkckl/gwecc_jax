import jax.numpy as jnp


def advance_of_periastron(x, e, η):
    k1 = 3 * x / (1 - e**2)
    k2 = 0.25 * x**2 * ((51 - 26 * η) * e**2 - 28 * η + 78) / (1 - e**2) ** 2
    k3 = (
        (1 / 128)
        * x**3
        * (
            (
                18240
                - 25376 * η
                + 492 * (jnp.pi**2) * η
                + 896 * η**2
                + (28128 - 27840 * η + 123 * (jnp.pi**2) * η + 5120 * η**2) * e**2
                + (2496 - 1760 * η + 1040 * η**2) * e**4
                + (1920 - 768 * η + (3840 - 1536 * η) * e**2) * jnp.sqrt(1 - e**2)
            )
        )
        / (1 - e**2) ** 3
    )
    return k1 + k2 + k3


def angular_eccentricity(x, e, η):
    ots = jnp.sqrt(1 - e**2)
    eφ = e * (
        1
        + x * (4 - η)
        + (x**2)
        * (
            4 * (-12 * (26 + 15 * ots) + η * (17 + 72 * ots + η))
            + (e**2) * (1152 + η * (-659 + 41 * η))
        )
        / (96 * (-1 + e**2))
        + (x**3)
        * (
            (
                -70 * e**4 * (-12288 + η * (11233 + 5 * η * (-383 + 3 * η)))
                + 20
                * (
                    1344 * (54 + 65 * ots)
                    + η
                    * (
                        861 * (1 + ots) * jnp.pi**2
                        + 4 * (-33431 - 29960 * ots - 3458 * η + 3360 * ots * η)
                    )
                )
                + 3
                * e**2
                * (
                    -8960 * (76 + 35 * ots)
                    + η
                    * (
                        -1435 * jnp.pi**2
                        + 4
                        * (
                            8 * (12983 + 5040 * ots)
                            + 35 * η * (-1319 + 32 * ots + 45 * η)
                        )
                    )
                )
            )
        )
        / (26880 * (-1 + e**2) ** 2)
    )

    return eφ
